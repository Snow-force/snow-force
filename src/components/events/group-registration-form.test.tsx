import { act, render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { beforeEach, expect, it, vi } from "vitest";
import { LanguageProvider } from "@/lib/language";
import { seedEvents } from "@/lib/events/seed";
import { previewProfile } from "@/lib/members/member-center-preview";
const create = vi.hoisted(() => vi.fn());
vi.mock("@/lib/registrations/v2/actions", () => ({ createEventBookingAction: create }));
vi.mock("@/lib/registrations/actions", () => ({ registerForEvent: vi.fn() }));
vi.mock("@/lib/payments/actions", () => ({ createCheckoutSessionAction: vi.fn() }));
vi.mock("@/components/members/event-booking-list", () => ({ EventBookingList: () => <div>Individual participant payments</div> }));
import { GroupRegistrationForm } from "./group-registration-form";
const event = { ...seedEvents[0], eventDate: "2026-11-07", registrationQuestions: [], allowProxyRegistrations: true, maxProxyRegistrations: 2 };
beforeEach(() => { create.mockReset(); document.cookie = "lang=en;path=/"; });
it("lets a non-attending booker add adult and minor friends with separate questionnaire and signer details", async () => {
  const user = userEvent.setup(); let finish: ((result: { success: true; booking: { id: string } }) => void) | undefined;
  async function pasteInto(field: HTMLElement, value: string) { await user.click(field); await user.paste(value); }
  create.mockImplementation(() => new Promise((resolve) => { finish = resolve; }));
  render(<LanguageProvider><GroupRegistrationForm event={event} profile={previewProfile} /></LanguageProvider>);
  await user.click(screen.getByRole("button", { name: "Add a friend" }));
  await pasteInto(screen.getByLabelText(/Name/), "Adult Friend");
  await pasteInto(screen.getByLabelText("Waiver signing email"), "friend@example.test");
  await user.click(screen.getByRole("button", { name: "Add a friend" }));
  await pasteInto(screen.getAllByLabelText(/Name/)[1], "Child Friend");
  await pasteInto(screen.getAllByLabelText("Waiver signing email")[1], "parent@example.test");
  expect(screen.queryByLabelText(/birth date/)).not.toBeInTheDocument();
  expect(screen.queryByLabelText("Guardian’s legal name")).not.toBeInTheDocument();
  expect(screen.queryByRole("button", { name: "Add a friend" })).not.toBeInTheDocument();
  await user.click(screen.getByRole("checkbox", { name: /I have permission/ }));
  await user.click(screen.getByRole("button", { name: "Save and continue to individual payments" }));
  expect(screen.getByRole("button", { name: "Saving participants…" })).toBeDisabled();
  const payload = { participants: JSON.parse(create.mock.calls[0][0].get("participants")) }; expect(payload.participants.map((p: { kind: string }) => p.kind)).toEqual(["proxy", "proxy"]);
  expect(payload.participants[1]).toMatchObject({ signerEmail: "parent@example.test", answers: { name: "Child Friend" } });
  expect(payload.participants[1].answers).not.toHaveProperty("dateOfBirth");
  await act(async () => finish?.({ success: true, booking: { id: "booking" } })); expect(await screen.findByText("Individual participant payments")).toBeInTheDocument();
});
